"""Exercise generated distribution drift and isolated skill resources."""
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]


class DistributionTests(unittest.TestCase):
    def test_native_validator_is_read_only_without_persistent_memory(self):
        validator = (ROOT / "agents/spec-design-validator.md").read_text()
        frontmatter = validator.split("---", 2)[1]
        self.assertNotRegex(frontmatter, r"(?m)^memory:")
        self.assertIn("Leave the working tree, index, and commit history exactly as you found them", validator)
        for instruction in ("Update your agent memory", "Use the Write and Edit tools",
                            "Persistent Agent Memory", "agent-memory/spec-design-validator"):
            with self.subTest(instruction=instruction):
                self.assertNotIn(instruction, validator)

    def test_native_agent_tools_are_restricted_by_frontmatter(self):
        frontmatter = {name: (ROOT / f"agents/{name}.md").read_text().split("---", 2)[1]
                       for name in ("spec-design-validator", "code-reviewer", "team-lead")}
        for name in ("spec-design-validator", "code-reviewer"):
            with self.subTest(agent=name):
                self.assertRegex(frontmatter[name], r"(?m)^disallowedTools:.*\bWrite\b.*\bEdit\b.*\bAgent\b")
                self.assertNotRegex(frontmatter[name], r"(?m)^tools:")
        self.assertRegex(frontmatter["team-lead"], r"(?m)^disallowedTools:.*\bAgent\b")
        for name, text in frontmatter.items():
            with self.subTest(agent=name):
                self.assertIn("# Generated by scripts/build-distribution.py", text)

    def test_team_lead_memory_suffix_defers_to_harness(self):
        team_lead = (ROOT / "agents/team-lead.md").read_text()
        for stale in ("`memory/` directory", "MEMORY.md is currently empty", "{ {"):
            with self.subTest(stale=stale):
                self.assertNotIn(stale, team_lead)

    def test_shared_role_paragraphs_are_identical(self):
        roles = [ROOT / "skills/agentic-loop/references/roles/code-reviewer.md",
                 ROOT / "skills/agentic-loop/references/roles/team-lead.md",
                 ROOT / "skills/validating-specs/references/validator-role.md"]
        dispatch_scope = re.compile(r"(?ms)^## Dispatch scope\n\n.*?\n(?=\n)")
        precedence = re.compile(r"(?m)^When the task prompt specifies an output format.*$")
        for pattern in (dispatch_scope, precedence):
            found = []
            for role in roles:
                matches = pattern.findall(role.read_text())
                with self.subTest(role=role.name, pattern=pattern.pattern):
                    self.assertEqual(len(matches), 1)
                found.extend(matches)
            self.assertEqual(len(set(found)), 1, pattern.pattern)

    def test_load_bearing_categories_are_identical(self):
        copies = [ROOT / "skills/agentic-loop/prompts/decision-rules.md",
                  ROOT / "skills/agentic-loop/references/roles/team-lead.md"]
        block = re.compile(r"(?s)<!-- load-bearing-categories:start -->\n.*?<!-- load-bearing-categories:end -->\n")
        found = []
        for copy in copies:
            matches = block.findall(copy.read_text())
            with self.subTest(copy=copy.name):
                self.assertEqual(len(matches), 1)
            found.extend(matches)
        self.assertEqual(len(set(found)), 1)

    def test_markdown_copies_carry_generated_marker(self):
        validation = ROOT / "skills/validating-specs"
        bundle = ROOT / "skills/agentic-loop/references/validation"
        copies = {ROOT / f"skills/{skill}/references/dispatch.md": validation / "references/dispatch.md"
                  for skill in ("agentic-loop", "writing-documentation")}
        for source in (validation / "references").glob("*.md"):
            copies[bundle / "references" / source.name] = source
        for source in (validation / "prompts").glob("*.md"):
            copies[bundle / "prompts" / source.name] = source
        for copy, source in copies.items():
            marker = (f"<!-- Generated from {source.relative_to(ROOT)} by scripts/build-distribution.py. "
                      "Maintainers: edit the canonical file and rebuild. -->\n\n")
            with self.subTest(copy=str(copy.relative_to(ROOT))):
                self.assertEqual(copy.read_text(), marker + source.read_text())
        workflow = (bundle / "workflow.md").read_text().split("\n")
        self.assertTrue(workflow[0].startswith("# "))
        self.assertTrue(workflow[2].startswith("<!-- Generated from skills/validating-specs/SKILL.md "))

    def test_committed_distribution_is_current(self):
        subprocess.run([sys.executable, str(ROOT / "scripts/build-distribution.py"), "--check"], check=True)

    def test_drift_is_detected_and_repaired(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = pathlib.Path(tmp)
            for directory in ("scripts", "skills", "adapters", "agents"):
                shutil.copytree(ROOT / directory, root / directory)
            target = root / "agents/spec-design-validator.md"
            target.write_text("stale\n")
            command = [sys.executable, str(root / "scripts/build-distribution.py")]
            self.assertNotEqual(subprocess.run(command + ["--check"], capture_output=True).returncode, 0)
            subprocess.run(command, check=True, capture_output=True)
            subprocess.run(command + ["--check"], check=True, capture_output=True)
            self.assertEqual(target.read_bytes(), (ROOT / "agents/spec-design-validator.md").read_bytes())

    def test_independent_skill_resources(self):
        required = {
            "agentic-loop": ["references/dispatch.md", "references/roles/code-reviewer.md", "references/roles/team-lead.md", "references/validation/workflow.md", "references/validation/references/validator-role.md", "references/validation/references/report-format.md", "references/validation/prompts/validator-instance.md", "scripts/check-gates.sh", "setup/hooks/lib-gates.sh", "scripts/init-run.sh"],
            "validating-specs": ["references/dispatch.md", "references/validator-role.md", "references/report-format.md", "prompts/validator-instance.md"],
            "writing-documentation": ["references/dispatch.md"],
        }
        for skill, resources in required.items():
            with self.subTest(skill=skill), tempfile.TemporaryDirectory() as tmp:
                root = pathlib.Path(tmp) / skill
                shutil.copytree(ROOT / "skills" / skill, root)
                for resource in resources:
                    self.assertTrue((root / resource).is_file(), resource)
                self.assertEqual(list(root.rglob("SKILL.md")), [root / "SKILL.md"])


if __name__ == "__main__":
    unittest.main()
