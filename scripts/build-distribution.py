#!/usr/bin/env python3
"""Build committed Claude adapters and self-contained skills (stdlib only)."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    validation = ROOT / "skills/validating-specs"
    loop = ROOT / "skills/agentic-loop"
    result = {}
    for name in ("spec-design-validator", "code-reviewer", "team-lead"):
        adapter = json.loads((ROOT / f"adapters/claude/{name}.json").read_text())
        role = validation / "references/validator-role.md" if name == "spec-design-validator" else loop / f"references/roles/{name}.md"
        body = role.read_text().replace("{{REPORT_FORMAT}}", (validation / "references/report-format.md").read_text().strip())
        result[ROOT / f"agents/{name}.md"] = (adapter["frontmatter"] + "\n<!-- Generated by scripts/build-distribution.py; edit canonical skill resources. -->\n\n" + body.rstrip() + "\n\n" + adapter["suffix"]).rstrip() + "\n"
    dispatch = (validation / "references/dispatch.md").read_text()
    for skill in ("agentic-loop", "writing-documentation"):
        result[ROOT / f"skills/{skill}/references/dispatch.md"] = dispatch
    bundle = loop / "references/validation"
    for directory in ("references", "prompts"):
        for source in sorted((validation / directory).rglob("*")):
            if source.is_file() and source.suffix == ".md":
                result[bundle / source.relative_to(validation)] = source.read_text()
    result[bundle / "workflow.md"] = validation.joinpath("SKILL.md").read_text().split("---", 2)[2].lstrip()
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    args = parser.parse_args()
    expected = outputs()
    bundle = ROOT / "skills/agentic-loop/references/validation"
    stale = set(bundle.rglob("*.md")) - expected.keys() if bundle.exists() else set()
    drift = [path for path, content in expected.items() if not path.exists() or path.read_text() != content]
    if args.check:
        for path in sorted(set(drift) | stale):
            print(f"Distribution drift: {path.relative_to(ROOT)}")
        return bool(drift or stale)
    for path in stale:
        path.unlink()
    for path in drift:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected[path])
    print(f"Updated {len(drift)} generated files; removed {len(stale)} stale files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
