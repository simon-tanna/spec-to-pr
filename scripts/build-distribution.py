#!/usr/bin/env python3
"""Build committed Claude adapters and self-contained skills (stdlib only)."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CANONICAL_REFERENCES = ROOT / "skills/spec-design-validator/references"
BUILDER = "scripts/build-distribution.py"


def marker(source):
    """Return the generated-file notice naming the canonical source of a Markdown copy."""
    return f"<!-- Generated from {source.relative_to(ROOT)} by scripts/build-distribution.py. Maintainers: edit the canonical file and rebuild. -->\n\n"


def standalone_payloads(body: str) -> dict[str, str]:
    """Wrap the canonical rubric for project-local Claude and Codex agents."""
    claude = json.loads((ROOT / "adapters/claude/spec-design-validator-standalone.json").read_text())
    codex = json.loads((ROOT / "adapters/codex/spec-design-validator.json").read_text())
    notice = marker(ROOT / "skills/spec-design-validator/SKILL.md")
    instructions = codex.get("prefix", "") + body + codex.get("suffix", "")
    # JSON escapes also work in TOML basic strings; TOML additionally requires DEL
    # to be escaped. Preserve Unicode to avoid JSON's non-BMP surrogate pairs.
    toml = "# Generated by scripts/build-distribution.py; edit canonical skill resources.\n"
    for key, value in (("name", codex["name"]), ("description", codex["description"]),
                       ("developer_instructions", instructions)):
        encoded = json.dumps(value, ensure_ascii=False).replace("\x7f", "\\u007f")
        toml += f"{key} = {encoded}\n"
    return {"claude.md": claude["frontmatter"].rstrip() + "\n\n" + notice
            + claude.get("prefix", "") + body + claude.get("suffix", ""),
            "codex.toml": toml}


def outputs():
    validation = ROOT / "skills/validating-specs"
    loop = ROOT / "skills/agentic-loop"
    result = {}
    canonical = ROOT / "skills/spec-design-validator/SKILL.md"
    text = canonical.read_text()
    name = canonical.relative_to(ROOT)
    if not text.startswith("---\n") or "\n---\n" not in text:
        raise SystemExit(f"{name}: missing YAML frontmatter delimited by ---")
    body = text.split("\n---\n", 1)[1].strip() + "\n"
    heading = "## Validation report format"
    if body.count(f"\n{heading}\n") != 1:
        raise SystemExit(f"{name}: expected exactly one '{heading}' section")
    report = heading + "\n" + body.split(f"\n{heading}\n", 1)[1]
    if "\n## " in report:
        raise SystemExit(f"{name}: '{heading}' must be the last ## section")
    report = report.rstrip() + "\n"
    result[validation / "references/validator-role.md"] = marker(canonical) + body
    result[validation / "references/report-format.md"] = marker(canonical) + report

    for skill in ("spec-design-validator", "validating-specs", "agentic-loop"):
        native = ROOT / "skills" / skill / "references/native-validator"
        for filename, content in standalone_payloads(body).items():
            result[native / filename] = content
        for source in sorted(CANONICAL_REFERENCES.iterdir()):
            if source.is_file() and not source.name.startswith("."):
                result[native / "references" / source.name] = (marker(source) if source.suffix == ".md" else "") + source.read_text()

    # Every canonical reference ships beside the copied role. JSON cannot hold an HTML
    # comment, so a JSON reference carries its own canonical notice in `$comment` and is
    # copied byte-for-byte.
    for source in sorted(CANONICAL_REFERENCES.iterdir()):
        if source.is_file() and not source.name.startswith("."):
            result[validation / "references" / source.name] = (marker(source) if source.suffix == ".md" else "") + source.read_text()

    for name in ("spec-design-validator", "code-reviewer", "team-lead"):
        adapter = json.loads((ROOT / f"adapters/claude/{name}.json").read_text())
        role = validation / "references/validator-role.md" if name == "spec-design-validator" else loop / f"references/roles/{name}.md"
        body = adapter.get("prefix", "") + (result[role] if role in result else role.read_text())
        frontmatter = adapter["frontmatter"].rstrip()
        assert frontmatter.endswith("\n---"), f"{name} frontmatter must end with ---"
        frontmatter = frontmatter[:-3] + "# Generated by scripts/build-distribution.py; edit canonical skill resources.\n---\n"
        result[ROOT / f"agents/{name}.md"] = (frontmatter + "\n" + body.rstrip() + "\n\n" + adapter["suffix"]).rstrip() + "\n"
    dispatch = validation / "references/dispatch.md"
    for skill in ("agentic-loop",):
        result[ROOT / f"skills/{skill}/references/dispatch.md"] = marker(dispatch) + dispatch.read_text()
    bundle = loop / "references/validation"
    for directory in ("references", "prompts"):
        sources = set((validation / directory).rglob("*")) | {p for p in result if p.parent == validation / directory}
        for source in sorted(sources):
            if "native-validator" in source.relative_to(validation).parts:
                continue
            if source in result:
                # Generated sources already carry their canonical notice (Markdown marker or
                # JSON `$comment`); copy them unchanged.
                result[bundle / source.relative_to(validation)] = result[source]
            elif source.is_file() and not source.name.startswith(".") and BUILDER not in source.read_text():
                # Hand-written sources gain a marker. A generated copy absent from result is an
                # orphan of a deleted canonical file: main() prunes it, so it must not re-ship.
                result[bundle / source.relative_to(validation)] = (marker(source) if source.suffix == ".md" else "") + source.read_text()
    workflow = validation / "SKILL.md"
    title, rest = workflow.read_text().split("---", 2)[2].lstrip().split("\n", 1)
    result[bundle / "workflow.md"] = title + "\n\n" + marker(workflow) + rest.lstrip("\n")
    return result


def is_generated_payload(path: Path) -> bool:
    """Recognize explicit generated ownership notices in native payload formats."""
    text = path.read_text()
    if path.suffix == ".md":
        return bool(re.search(r"(?m)^<!-- Generated from \S+ by scripts/build-distribution\.py\. Maintainers: edit the canonical file and rebuild\. -->$", text))
    if path.suffix == ".toml":
        return text.startswith("# Generated by scripts/build-distribution.py; edit canonical skill resources.\n")
    if path.suffix == ".json":
        try:
            document = json.loads(text)
        except json.JSONDecodeError:
            return False
        comment = document.get("$comment") if isinstance(document, dict) else None
        return isinstance(comment, str) and bool(re.fullmatch(r"Canonical source: \S+\. Copies elsewhere are generated by scripts/build-distribution\.py; edit the canonical file and rebuild\.", comment))
    return False


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    args = parser.parse_args()
    expected = outputs()
    bundle = ROOT / "skills/agentic-loop/references/validation"
    stale = {p for p in bundle.rglob("*") if p.is_file()} - expected.keys() if bundle.exists() else set()
    # validating-specs/references mixes hand-written files with generated copies; only a
    # file that names this builder is ours to prune once its canonical source is gone.
    copies = ROOT / "skills/validating-specs/references"
    stale |= {p for p in copies.iterdir() if p.is_file() and BUILDER in p.read_text()} - expected.keys()
    for skill in ("spec-design-validator", "validating-specs", "agentic-loop"):
        native = ROOT / "skills" / skill / "references/native-validator"
        if native.exists():
            stale |= {p for p in native.rglob("*") if p.is_file() and is_generated_payload(p)} - expected.keys()
    drift = [path for path, content in expected.items() if not path.exists() or path.read_text() != content]
    if args.check:
        for path in sorted(set(drift) | stale):
            print(f"Distribution drift: {path.relative_to(ROOT)}")
        return bool(drift or stale)
    for path in stale:
        path.unlink()
    for path in drift:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected[path])
    print(f"Updated {len(drift)} generated files; removed {len(stale)} stale files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
