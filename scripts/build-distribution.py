#!/usr/bin/env python3
"""Build committed Claude adapters and self-contained skills (stdlib only)."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def marker(source):
    """Return the generated-file notice naming the canonical source of a Markdown copy."""
    return f"<!-- Generated from {source.relative_to(ROOT)} by scripts/build-distribution.py. Maintainers: edit the canonical file and rebuild. -->\n\n"


def outputs():
    validation = ROOT / "skills/validating-specs"
    loop = ROOT / "skills/agentic-loop"
    result = {}
    canonical = ROOT / "skills/spec-design-validator/SKILL.md"
    text = canonical.read_text()
    name = canonical.relative_to(ROOT)
    if not text.startswith("---\n") or "\n---\n" not in text:
        raise SystemExit(f"{name}: missing YAML frontmatter delimited by ---")
    body = text.split("\n---\n", 1)[1].strip() + "\n"
    heading = "## Validation report format"
    if body.count(f"\n{heading}\n") != 1:
        raise SystemExit(f"{name}: expected exactly one '{heading}' section")
    report = heading + "\n" + body.split(f"\n{heading}\n", 1)[1]
    if "\n## " in report:
        raise SystemExit(f"{name}: '{heading}' must be the last ## section")
    report = report.rstrip() + "\n"
    result[validation / "references/validator-role.md"] = marker(canonical) + body
    result[validation / "references/report-format.md"] = marker(canonical) + report

    schema = ROOT / "skills/spec-design-validator/references/ledger.schema.json"
    result[validation / "references/ledger.schema.json"] = schema.read_text()

    for name in ("spec-design-validator", "code-reviewer", "team-lead"):
        adapter = json.loads((ROOT / f"adapters/claude/{name}.json").read_text())
        role = validation / "references/validator-role.md" if name == "spec-design-validator" else loop / f"references/roles/{name}.md"
        body = adapter.get("prefix", "") + (result[role] if role in result else role.read_text())
        frontmatter = adapter["frontmatter"].rstrip()
        assert frontmatter.endswith("\n---"), f"{name} frontmatter must end with ---"
        frontmatter = frontmatter[:-3] + "# Generated by scripts/build-distribution.py; edit canonical skill resources.\n---\n"
        result[ROOT / f"agents/{name}.md"] = (frontmatter + "\n" + body.rstrip() + "\n\n" + adapter["suffix"]).rstrip() + "\n"
    dispatch = validation / "references/dispatch.md"
    for skill in ("agentic-loop",):
        result[ROOT / f"skills/{skill}/references/dispatch.md"] = marker(dispatch) + dispatch.read_text()
    bundle = loop / "references/validation"
    for directory in ("references", "prompts"):
        sources = set((validation / directory).rglob("*")) | {p for p in result if p.parent == validation / directory}
        for source in sorted(sources):
            if (source.is_file() or source in result) and source.suffix in (".md", ".json"):
                # Generated sources already carry their canonical marker; copy them unchanged.
                result[bundle / source.relative_to(validation)] = result[source] if source in result else (marker(source) if source.suffix == ".md" else "") + source.read_text()
    workflow = validation / "SKILL.md"
    title, rest = workflow.read_text().split("---", 2)[2].lstrip().split("\n", 1)
    result[bundle / "workflow.md"] = title + "\n\n" + marker(workflow) + rest.lstrip("\n")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    args = parser.parse_args()
    expected = outputs()
    bundle = ROOT / "skills/agentic-loop/references/validation"
    stale = {p for p in bundle.rglob("*") if p.suffix in (".md", ".json")} - expected.keys() if bundle.exists() else set()
    drift = [path for path, content in expected.items() if not path.exists() or path.read_text() != content]
    if args.check:
        for path in sorted(set(drift) | stale):
            print(f"Distribution drift: {path.relative_to(ROOT)}")
        return bool(drift or stale)
    for path in stale:
        path.unlink()
    for path in drift:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected[path])
    print(f"Updated {len(drift)} generated files; removed {len(stale)} stale files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
